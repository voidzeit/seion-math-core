"""Cutting-plane LP evaluation of k=4 topology constants on exact finite reductions (real field).

Reductions (see report):
 BBR : value(a,b) = max_g max_{B,C} cos g (Fa'B Fb - ca cb B11) + sin g Fa'C Fb
       s.t. w1 x'By + w2 x'Cy <= 1  for all unit x,y,w in R^2,   |C11| <= eta
 STAR: value(a,b,c) = max_W <W, Fa(x)Fb(x)Fc - r e1(x)e1(x)e1>  s.t. W(x,y,z) <= 1 for unit x,y,z
For fixed angles (and g) these are LPs in 8 variables; constraints generated by a separation oracle
(grid + local refinement). Final LP value is an upper estimate; dividing the optimal W by its verified
norm gives an admissible lower value, so each value is bracketed.
"""
import numpy as np, math, sys, json
from scipy.optimize import linprog, minimize_scalar

def unit(t):
    return np.array([math.cos(t), math.sin(t)])

S1 = np.linspace(0, np.pi, 2048, endpoint=False)
X1 = np.stack([np.cos(S1), np.sin(S1)], 1)

def bil_norm_and_argmax(B, C):
    # max_x sigma_max([x'B; x'C]) ; returns norm and maximizing (x, y, w)
    rows = np.stack([X1 @ B, X1 @ C], 1)            # (m,2,2)
    sv = np.linalg.svd(rows, compute_uv=False)[:, 0]
    i = int(np.argmax(sv))
    f = lambda s: -np.linalg.svd(np.stack([unit(s) @ B, unit(s) @ C]), compute_uv=False)[0]
    r = minimize_scalar(f, bounds=(S1[i] - 2e-3, S1[i] + 2e-3), method="bounded", options={"xatol": 1e-13})
    s = r.x if -r.fun >= sv[i] else S1[i]
    M = np.stack([unit(s) @ B, unit(s) @ C])
    U, sig, Vt = np.linalg.svd(M)
    return sig[0], unit(s), Vt[0], U[:, 0]

def bbr_lp(a, b, g, eta, iters=200, tol=1e-10):
    Fa, Fb = unit(a), unit(b)
    ca_cb = math.cos(a) * math.cos(b)
    # variable order: B00 B01 B10 B11 C00 C01 C10 C11
    obj = np.concatenate([math.cos(g) * (np.outer(Fa, Fb).ravel() - ca_cb * np.array([1, 0, 0, 0])),
                          math.sin(g) * np.outer(Fa, Fb).ravel()])
    cons = []
    for s in np.linspace(0, np.pi, 6, endpoint=False):
        for u in np.linspace(0, np.pi, 6, endpoint=False):
            for w in np.linspace(0, 2 * np.pi, 8, endpoint=False):
                xy = np.outer(unit(s), unit(u)).ravel(); ww = unit(w)
                cons.append(np.concatenate([ww[0] * xy, ww[1] * xy]))
    bounds = [(-2, 2)] * 4 + [(-eta, eta)] + [(-2, 2)] * 3   # C00 = closure entry on (Rhat_a, Rhat_b)
    for it in range(iters):
        res = linprog(-obj, A_ub=np.array(cons), b_ub=np.ones(len(cons)), bounds=bounds, method="highs")
        z = res.x; B, C = z[:4].reshape(2, 2), z[4:].reshape(2, 2)
        N, x, y, w = bil_norm_and_argmax(B, C)
        if N <= 1 + tol:
            break
        xy = np.outer(x, y).ravel()
        cons.append(np.concatenate([w[0] * xy, w[1] * xy]))
    upper = -res.fun
    lower = upper / max(N, 1.0)       # rescaled map is admissible (closure only shrinks)
    return upper, lower, (B / max(N, 1), C / max(N, 1))

S2 = np.linspace(0, np.pi, 256, endpoint=False)
X2 = np.stack([np.cos(S2), np.sin(S2)], 1)

def spec3_and_argmax(W):
    V = np.einsum('ijk,pi,qj->pqk', W, X2, X2)
    n = np.sqrt((V ** 2).sum(-1))
    p, q = np.unravel_index(int(np.argmax(n)), n.shape)
    s, u = S2[p], S2[q]
    # local refinement by coordinate ascent
    val = n[p, q]
    for h in (2e-3, 5e-4, 1e-4, 2e-5, 4e-6, 1e-6):
        improved = True
        while improved:
            improved = False
            for ds, du in ((h, 0), (-h, 0), (0, h), (0, -h), (h, h), (-h, -h), (h, -h), (-h, h)):
                v = np.linalg.norm(np.einsum('ijk,i,j->k', W, unit(s + ds), unit(u + du)))
                if v > val:
                    val, s, u, improved = v, s + ds, u + du, True
    z = np.einsum('ijk,i,j->k', W, unit(s), unit(u)); z = z / np.linalg.norm(z)
    return val, unit(s), unit(u), z

def star_lp(a, b, c, iters=400, tol=1e-9):
    F = [unit(t) for t in (a, b, c)]
    r = math.cos(a) * math.cos(b) * math.cos(c)
    T = np.einsum('i,j,k->ijk', *F); T[0, 0, 0] -= r
    obj = T.ravel()
    cons = []
    for s in np.linspace(0, np.pi, 6, endpoint=False):
        for u in np.linspace(0, np.pi, 6, endpoint=False):
            for w in np.linspace(0, 2 * np.pi, 6, endpoint=False):
                cons.append(np.einsum('i,j,k->ijk', unit(s), unit(u), unit(w)).ravel())
    for it in range(iters):
        res = linprog(-obj, A_ub=np.array(cons), b_ub=np.ones(len(cons)), bounds=[(-3, 3)] * 8, method="highs")
        W = res.x.reshape(2, 2, 2)
        N, x, y, z = spec3_and_argmax(W)
        if N <= 1 + tol:
            break
        cons.append(np.einsum('i,j,k->ijk', x, y, z).ravel())
    upper = -res.fun
    return upper, upper / max(N, 1.0), W / max(N, 1.0)

def chain_val(n, th):
    return abs(1 - (math.cos(th) * complex(math.cos(th), math.sin(th))) ** n)

if __name__ == "__main__":
    mode, eta = sys.argv[1], float(sys.argv[2])
    TH = math.asin(eta)
    thgrid = np.linspace(0, TH, 2001)
    G4 = max(chain_val(3, t) for t in thgrid)
    out = {"mode": mode, "eta": eta, "chain_G4": G4, "rows": []}
    if mode == "bbr":
        best = (0, 0, None)
        fr = np.linspace(0.25, 1.0, 7)
        for fa in fr:
            for fb in fr:
                if fb < fa:
                    continue
                a, b = fa * TH, fb * TH
                gbest = max(((bbr_lp(a, b, g, eta, iters=60)[1], g) for g in np.linspace(0, np.pi, 13)), key=lambda t: t[0])
                g0 = gbest[1]
                r = minimize_scalar(lambda g: -bbr_lp(a, b, g, eta)[1], bounds=(g0 - np.pi / 12, g0 + np.pi / 12),
                                    method="bounded", options={"xatol": 1e-6})
                up, lo, _ = bbr_lp(a, b, r.x, eta)
                out["rows"].append([fa, fb, float(r.x), up, lo])
                if lo > best[0]:
                    best = (lo, up, (a, b, float(r.x)))
        out.update(best_lower=best[0], best_upper_at_best=best[1], best_args=best[2])
    else:
        best = (0, 0, None)
        fr = np.linspace(0.25, 1.0, 5)
        for fa in fr:
            for fb in fr:
                for fc in fr:
                    if not (fa <= fb <= fc):
                        continue
                    up, lo, _ = star_lp(fa * TH, fb * TH, fc * TH)
                    out["rows"].append([fa, fb, fc, up, lo])
                    if lo > best[0]:
                        best = (lo, up, (fa * TH, fb * TH, fc * TH))
        # also the chain-optimal equal angle
        topt = thgrid[int(np.argmax([chain_val(3, t) for t in thgrid]))]
        up, lo, _ = star_lp(topt, topt, topt)
        out["rows"].append(["chain_opt", float(topt), up, lo])
        if lo > best[0]:
            best = (lo, up, (topt,) * 3)
        out.update(best_lower=best[0], best_upper_at_best=best[1], best_args=best[2])
    print(json.dumps({k: v for k, v in out.items() if k != "rows"}), flush=True)
    json.dump(out, open(f"topo_lp_{mode}_eta{eta:.4f}.json", "w"), indent=1)
